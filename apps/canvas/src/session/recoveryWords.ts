/** Eleven bits per word: 2048 = 2^11. */
const BITS_PER_WORD = 11;

/** Entropy sizes the phrase format supports: 16 bytes -> 12 words, 32 -> 24. */
const KEY_BYTES = new Set([16, 32]);

const WORD_INDEX = new Map<string, number>(RECOVERY_WORDLIST.map((word, index) => [word, index]));

export type RecoveryWordsResult = { ok: true; key: string } | { ok: false; problem: string };

/** Lowercase and strip accents/punctuation: what a person might type by hand. */
function normalizeWord(word: string): string {
  return word
    .normalize("NFKD")
    .toLowerCase()
    .replace(/[^a-z]/gu, "");
}

function decodeKey(key: string): Uint8Array<ArrayBuffer> | null {
  const normalized = key.trim().replace(/-/gu, "+").replace(/_/gu, "/");
  const padded = normalized + "=".repeat((4 - (normalized.length % 4)) % 4);
  let binary: string;
  try {
    binary = atob(padded);
  } catch {
    return null;
  }
  const bytes = new Uint8Array(binary.length);
  for (let index = 0; index < binary.length; index += 1) bytes[index] = binary.charCodeAt(index);
  return KEY_BYTES.has(bytes.length) ? bytes : null;
}

function bytesToBits(bytes: Uint8Array): number[] {
  const bits: number[] = [];
  for (const byte of bytes) {
    for (let shift = 7; shift >= 0; shift -= 1) bits.push((byte >> shift) & 1);
  }
  return bits;
}

function bitsToBytes(bits: readonly number[]): Uint8Array<ArrayBuffer> {
  const bytes = new Uint8Array(Math.floor(bits.length / 8));
  for (const [index, bit] of bits.entries()) {
    if (bit === 1) bytes[index >> 3] = (bytes[index >> 3] ?? 0) | (1 << (7 - (index % 8)));
  }
  return bytes;
}

async function checksumBits(bytes: Uint8Array<ArrayBuffer>, count: number): Promise<number[]> {
  const digest = new Uint8Array(await crypto.subtle.digest("SHA-256", bytes));
  return bytesToBits(digest).slice(0, count);
}

/**
 * The key as words: 12 for a 16-byte key, 24 for the 32-byte owner key. Throws
 * on anything else, because there is no phrase shape for it and silently
 * truncating a key would hand back words that cannot restore access.
 */
export async function encodeKey(key: string): Promise<string> {
  const bytes = decodeKey(key);
  if (!bytes) throw new Error("Recovery words can only be made from a 16 or 32 byte key.");

  const checksum = await checksumBits(bytes, bytes.length / 4);
  const bits = [...bytesToBits(bytes), ...checksum];
  const words: string[] = [];
  for (let offset = 0; offset < bits.length; offset += BITS_PER_WORD) {
    let index = 0;
    for (const bit of bits.slice(offset, offset + BITS_PER_WORD)) index = (index << 1) | bit;
    const word = RECOVERY_WORDLIST[index];
    if (word === undefined) throw new Error("The recovery word list is incomplete.");
    words.push(word);
  }
  return words.join(" ");
}

/**
 * The key a phrase stands for, or one readable reason it cannot be used. Every
 * failure is a sentence the protected screen can show as-is: a wrong count, an
 * unknown word (named, with its position) or a checksum mismatch.
 */
export async function decodeWords(input: string | readonly string[]): Promise<RecoveryWordsResult> {
  const raw = (typeof input === "string" ? input.split(/\s+/u) : [...input])
    .map((word) => word.trim())
    .filter((word) => word.length > 0);

  if (raw.length !== 12 && raw.length !== 24) {
    return {
      ok: false,
      problem: `Recovery words are 12 or 24 words; this has ${raw.length}.`,
    };
  }

  const indices: number[] = [];
  for (const [position, word] of raw.entries()) {
    const index = WORD_INDEX.get(normalizeWord(word));
    if (index === undefined) {
      return {
        ok: false,
        problem: `"${word}" is not a recovery word (word ${position + 1}). Check the spelling.`,
      };
    }
    indices.push(index);
  }

  const bits: number[] = [];
  for (const index of indices) {
    for (let shift = BITS_PER_WORD - 1; shift >= 0; shift -= 1) bits.push((index >> shift) & 1);
  }

  const checksumCount = indices.length / 3;
  const entropy = bitsToBytes(bits.slice(0, bits.length - checksumCount));
  const expected = await checksumBits(entropy, checksumCount);
  const actual = bits.slice(bits.length - checksumCount);
  if (expected.some((bit, index) => bit !== actual[index])) {
    return {
      ok: false,
      problem:
        "These recovery words do not match their checksum, so one word is probably mistyped. Check each word against your copy.",
    };
  }

  return { ok: true, key: ownerKeyFromBytes(entropy) };
}

/** The .txt body: the words, plus what they are for and which workspace. */
export function recoveryWordsDocument(
  workspaceId: string,
  phrase: string,
  createdAt = new Date(),
): string {
  const words = phrase.split(" ");
  const numbered = words.map((word, index) => `${index + 1}. ${word}`).join("\n");
  return [
    "Suite workspace recovery words",
    "",
    `Workspace: ${workspaceId}`,
    `Created: ${createdAt.toISOString()}`,
    "",
    "Anyone with these words has owner access to the workspace. Keep this file",
    "away from document backups, and write the words down in order.",
    "",
    numbered,
    "",
    "Type them back in the workspace's protected screen, under",
    '"Recover with recovery words".',
    "",
  ].join("\n");
}
