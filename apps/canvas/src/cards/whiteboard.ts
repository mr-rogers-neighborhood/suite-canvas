import type {
  Card,
  CardType,
  DrawingElement,
  FieldDefinition,
  WorkspaceDocument,
} from "@suite/graph";

/**
 * The built-in type id is stable so the renderer can recognise the card. The
 * label is "Sketch" everywhere a reader can see it; the id stays `whiteboard`
 * so every existing document keeps its cards without a migration.
 */
export const WHITEBOARD_TYPE_ID = "whiteboard";

/** User-facing names of the built-in type. */
export const SKETCH_TYPE_NAME = "Sketch";
export const SKETCH_TYPE_PLURAL = "Sketches";

/** The two ways a sketch card is painted on the board. */
export const SKETCH_DISPLAY_MODES = ["framed", "seamless"] as const;
export type SketchDisplayMode = (typeof SKETCH_DISPLAY_MODES)[number];

/**
 * Display mode is a value on a field of the sketch's own type — the same route
 * the portal's board value takes (`portal-board`), not a new record field and
 * not a drawing key. Field ids are generated by `addField`, so the field's name
 * is the stable anchor the canvas looks it up by.
 */
export const SKETCH_DISPLAY_FIELD_NAME = "Display";
const SKETCH_DISPLAY_OPTION_LABELS: Record<SketchDisplayMode, string> = {
  framed: "Framed",
  seamless: "Seamless",
};

export function isSketchDisplayMode(value: unknown): value is SketchDisplayMode {
  return value === "framed" || value === "seamless";
}

/** The display-mode field on a type, or undefined for a type that has none. */
export function sketchDisplayField(type: CardType | undefined): FieldDefinition | undefined {
  return type?.fields.find((field) => field.name === SKETCH_DISPLAY_FIELD_NAME);
}

/**
 * Sketches are created on demand instead of seeded, so an existing workspace
 * does not grow a new type until someone asks for a drawing. The call is
 * idempotent and additive: it upgrades the old "Whiteboard" label (the rename
 * is a label only), and it adds the display field once.
 */
export function ensureWhiteboardType(workspace: WorkspaceDocument): CardType {
  const existing = workspace.getType(WHITEBOARD_TYPE_ID);
  const type =
    existing ??
    workspace.createType({
      id: WHITEBOARD_TYPE_ID,
      name: SKETCH_TYPE_NAME,
      pluralName: SKETCH_TYPE_PLURAL,
      glyph: "\u25a7",
    });

  // A workspace created before the rename still carries the old label; a name
  // the user chose themselves is left alone.
  if (type.name === "Whiteboard") {
    workspace.updateType(type.id, { name: SKETCH_TYPE_NAME, pluralName: SKETCH_TYPE_PLURAL });
  } else if (type.pluralName === "Whiteboards") {
    workspace.updateType(type.id, { pluralName: SKETCH_TYPE_PLURAL });
  }

  if (!sketchDisplayField(type)) {
    workspace.addField(type.id, {
      name: SKETCH_DISPLAY_FIELD_NAME,
      kind: "select",
      options: [SKETCH_DISPLAY_OPTION_LABELS.framed, SKETCH_DISPLAY_OPTION_LABELS.seamless],
    });
  }

  return workspace.getType(WHITEBOARD_TYPE_ID) ?? type;
}

export function isWhiteboardCard(card: Pick<Card, "primaryTypeId"> | undefined): boolean {
  return card?.primaryTypeId === WHITEBOARD_TYPE_ID;
}

/**
 * The display mode stored on one card. Anything unreadable (a card created
 * before the field existed, an option a user removed) reads as `framed`, which
 * is how sketches have always painted.
 */
export function readSketchDisplay(
  workspace: Pick<WorkspaceDocument, "getType">,
  card: Pick<Card, "primaryTypeId" | "properties"> | null | undefined,
): SketchDisplayMode {
  if (!isWhiteboardCard(card ?? undefined)) return "framed";
  const type = card?.primaryTypeId ? workspace.getType(card.primaryTypeId) : undefined;
  const field = sketchDisplayField(type);
  if (!field || !card) return "framed";
  const value = card.properties[field.id];
  if (typeof value !== "string" || value.length === 0) return "framed";
  const option = field.options.find((entry) => entry.id === value);
  const raw = (option?.label ?? value).trim().toLowerCase();
  return isSketchDisplayMode(raw) ? raw : "framed";
}

/** Writes the display mode as an ordinary field value; one commit, one undo. */
export function setSketchDisplay(
  workspace: WorkspaceDocument,
  cardId: string,
  mode: SketchDisplayMode,
): void {
  const card = workspace.getCard(cardId);
  if (!isWhiteboardCard(card)) return;
  const type = card?.primaryTypeId ? workspace.getType(card.primaryTypeId) : undefined;
  const field = sketchDisplayField(type);
  const option = field?.options.find(
    (entry) =>
      entry.label.trim().toLowerCase() === SKETCH_DISPLAY_OPTION_LABELS[mode].toLowerCase(),
  );
  if (!field || !option) return;
  if (card?.properties[field.id] === option.id) return;
  workspace.setProperty(cardId, field.id, option.id);
}

/** One scene update waiting for its stroke to end. */
export interface SketchCommitBatcher<T> {
  /** Records the newest scene. A timer lands it when no gesture is running. */
  schedule(value: T): void;
  /** A pointer went down: no write may land mid-stroke. */
  beginGesture(): void;
  /** The pointer came up: the whole stroke lands as one commit. */
  endGesture(): void;
  flush(): void;
  dispose(): void;
  readonly pending: boolean;
}

/**
 * Batches editor output into one commit per gesture. Excalidraw reports every
 * pointer sample of a freehand stroke; writing each one would put hundreds of
 * entries in the undo stack for one line. A gesture suppresses the idle timer
 * and commits once on pointer-up; keyboard-only edits still settle on the timer.
 */
export function createSketchCommitBatcher<T>(
  commit: (value: T) => void,
  idleMs = 300,
): SketchCommitBatcher<T> {
  let pending: { value: T } | null = null;
  let timer: ReturnType<typeof setTimeout> | null = null;
  let gesture = false;

  function cancel(): void {
    if (timer === null) return;
    clearTimeout(timer);
    timer = null;
  }

  function flush(): void {
    cancel();
    if (pending === null) return;
    const { value } = pending;
    pending = null;
    commit(value);
  }

  return {
    schedule(value) {
      pending = { value };
      if (gesture) return;
      cancel();
      timer = setTimeout(flush, idleMs);
    },
    beginGesture() {
      gesture = true;
      cancel();
    },
    endGesture() {
      gesture = false;
      flush();
    },
    flush,
    dispose() {
      cancel();
      pending = null;
    },
    get pending() {
      return pending !== null;
    },
  };
}

/**
 * Drops the keys Excalidraw writes as `undefined`.
 *
 * Excalidraw builds an element with every optional key present and `undefined`
 * for the ones it did not use, `customData` being the usual one. The drawing
 * schema refuses an explicit `undefined`, because the CRDT cannot store one and a
 * reader would get a key it cannot tell from an absent one. So the boundary drops
 * those keys, and nothing else about the element is touched.
 */
function withoutUndefined(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(withoutUndefined);
  if (value === null || typeof value !== "object") return value;
  const prototype = Object.getPrototypeOf(value);
  // Something with its own prototype is not ours to rewrite: let the schema say so.
  if (prototype !== Object.prototype && prototype !== null) return value;
  const copy: Record<string, unknown> = {};
  for (const [key, entry] of Object.entries(value)) {
    if (entry === undefined) continue;
    copy[key] = withoutUndefined(entry);
  }
  return copy;
}

/** One Excalidraw element as the graph will store it. */
export function toDrawingElement(element: DrawingElement): DrawingElement {
  return withoutUndefined(element) as DrawingElement;
}
