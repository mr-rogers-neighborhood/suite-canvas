#!/usr/bin/env node
/**
 * Generates the four section dashboards under `docs/`.
 *
 * Each index is a table of that section's pages, newest first. The date comes
 * from the file's last git commit, or its mtime while the page is still
 * uncommitted, so a reader can tell which pages changed recently without a
 * second source of truth.
 *
 *   node scripts/generate-doc-indexes.mjs            # rewrite the indexes
 *   node scripts/generate-doc-indexes.mjs --check    # exit 1 when stale
 */
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

const SECTIONS = [
  {
    dir: "tutorials",
    title: "Tutorials",
    intro:
      "Learn by doing. Each page is one guided path to a first success, with nothing to decide first.",
  },
  {
    dir: "how-to",
    title: "How-to",
    intro: "One task at a time: the steps for a job you already know you need to do.",
  },
  {
    dir: "reference",
    title: "Reference",
    intro: "Facts to look up: the data model, the commands, the quotas, the security boundary.",
  },
  {
    dir: "explanation",
    title: "Explanation",
    intro:
      "Why the product and the code are shaped this way, including the decisions that produced them.",
  },
];

const GENERATED = "<!-- generated by scripts/generate-doc-indexes.mjs; do not edit -->";

function repoPath(path) {
  return relative(root, path).split(sep).join("/");
}

/**
 * Whether this tree can answer "when was this page last committed".
 *
 * A source archive, a container export and a `git archive` all lack `.git`, and the index is a
 * table of *commit* dates. Falling back to the file's mtime there is worse than useless: an
 * export unpacks every file at the same second, so every date in the table becomes that second,
 * the rows re-sort alphabetically, and running the generator in that tree rewrites the real dates
 * to today's. That is how a documentation index quietly becomes wrong.
 *
 * So the date comes from git or from the index already on disk. Never from mtime.
 */
const gitAvailable = (() => {
  try {
    execFileSync("git", ["rev-parse", "--git-dir"], { cwd: root, stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
})();

/** The commit date of a page, or null when this tree cannot tell. */
function lastModified(path) {
  if (!gitAvailable) return null;
  try {
    const out = execFileSync("git", ["log", "-1", "--format=%cI", "--", repoPath(path)], {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
    if (out) return out;
  } catch {
    // An untracked page has no commit yet.
  }
  return null;
}

function titleAndSummary(path) {
  const raw = readFileSync(path, "utf8").replace(/<!--[\s\S]*?-->/g, "");
  const lines = raw.split("\n");
  const heading = lines.find((line) => line.startsWith("# "));
  const title = heading ? heading.slice(2).trim() : repoPath(path).replace(/\.md$/, "");
  let start = heading ? lines.indexOf(heading) + 1 : 0;
  if (/^ADR-/.test(title)) {
    const decision = lines.findIndex(
      (line, index) => index > start && line.trim() === "## Decision",
    );
    if (decision !== -1) start = decision + 1;
  }
  let paragraph = "";
  let fenced = false;
  let inList = false;
  for (const line of lines.slice(start)) {
    if (/^\s*(```|~~~)/.test(line)) {
      fenced = !fenced;
      continue;
    }
    if (fenced) continue;
    const trimmed = line.trim();
    if (trimmed === "") {
      if (paragraph) break;
      inList = false;
      continue;
    }
    if (/^(\||#|>)/.test(trimmed)) {
      if (paragraph) break;
      continue;
    }
    const listItem = /^(?:[-*] |\d+\. )(.+)$/.exec(trimmed);
    if (listItem) {
      if (inList && paragraph) break;
      paragraph = listItem[1];
      inList = true;
      continue;
    }
    if (inList) break;
    paragraph = paragraph ? `${paragraph} ${trimmed}` : trimmed;
  }
  const summary = paragraph
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/[`*]/g, "")
    .replace(/\s+/g, " ")
    .trim();
  return { title, summary: summary.length > 150 ? `${summary.slice(0, 150).trimEnd()}…` : summary };
}

function pagesIn(section) {
  const base = join(root, "docs", section.dir);
  const pages = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.name.startsWith(".") || entry.name === "index.md") continue;
      if (entry.name === "README.md" || entry.name === "TEMPLATE.md") continue;
      const path = join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(path);
        continue;
      }
      if (!entry.name.endsWith(".md")) continue;
      const { title, summary } = titleAndSummary(path);
      const rel = relative(base, path).split(sep).join("/");
      pages.push({
        path,
        rel,
        title,
        summary,
        // Resolved before sorting: the committed index is ordered newest first, and a title
        // order would rewrite every row's position even when nothing about a page changed.
        date: lastModified(path) ?? "",
        group:
          section.dir === "explanation" && relative(base, path).startsWith("decisions")
            ? "Decisions"
            : section.dir === "explanation"
              ? "Direction"
              : null,
      });
    }
  };
  walk(base);
  // Newest first. With no dates to compare, title is the only stable order, and the committed
  // index is compared on content rather than reshuffled.
  return pages.sort((a, b) => b.date.localeCompare(a.date) || a.title.localeCompare(b.title));
}

function table(pages) {
  const rows = pages.map(
    (page) =>
      `| [${page.title}](${page.rel}) | ${page.summary || "—"} | ${page.date.slice(0, 10)} |`,
  );
  return ["| Article | What it covers | Updated |", "| --- | --- | --- |", ...rows].join("\n");
}

function render(section) {
  const pages = pagesIn(section);
  const parts = [GENERATED, "", `# ${section.title}`, "", section.intro, ""];
  if (section.dir === "explanation") {
    for (const group of ["Direction", "Decisions"]) {
      const groupPages = pages.filter((page) => page.group === group);
      if (groupPages.length === 0) continue;
      parts.push(`## ${group}`, "", table(groupPages), "");
    }
  } else {
    parts.push(table(pages), "");
  }
  return `${parts.join("\n").trimEnd()}\n`;
}

if (!gitAvailable) {
  // A row's date is a commit date and the rows are ordered by its *time* within that day, which
  // the index does not store. Without history the table is neither verifiable nor regenerable, so
  // this says so rather than comparing against a guess.
  if (check) {
    console.log("doc indexes: skipped, this tree has no git history to date them from");
    process.exit(0);
  }
  console.error(
    "doc indexes cannot be written here: a row's date and order come from commit timestamps and " +
      "this tree has no .git. Run it in a checkout.",
  );
  process.exit(1);
}

let stale = 0;
for (const section of SECTIONS) {
  const target = join(root, "docs", section.dir, "index.md");
  const next = render(section);
  const current = (() => {
    try {
      return readFileSync(target, "utf8");
    } catch {
      return "";
    }
  })();
  if (current === next) continue;
  stale += 1;
  if (check) {
    console.error(`${repoPath(target)} is out of date`);
  } else {
    writeFileSync(target, next);
    console.log(`wrote ${repoPath(target)}`);
  }
}

if (check && stale > 0) process.exit(1);
if (check) console.log("doc indexes are up to date");
