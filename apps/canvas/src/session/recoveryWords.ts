/**
 * Printable recovery words for an owner key.
 *
 * The format is BIP-39 in shape but not interchangeable with it: eleven bits
 * per word from Suite's own fixed list, plus a checksum, so a phrase read off
 * paper rebuilds the exact key without any server, account or network.
 *
 * A 32-byte owner key carries 256 bits of entropy. Twenty-four words hold
 * 24 x 11 = 264 bits, of which 256 are the key and 8 are checksum. A twelve
 * word phrase holds only 132 bits, so it can carry a 16-byte key (128 + 4) but
 * never the 32-byte owner key; `encodeKey` picks the length from the key and
 * the owner key therefore always becomes 24 words.
 *
 * Checksum: the first (entropyBits / 32) bits of SHA-256(entropy) are appended
 * to the entropy before the bit stream is split into 11-bit groups. A mistyped
 * word changes the recovered entropy, so its checksum matches only about once
 * in 256 (24 words) or once in 16 (12 words) and the phrase is refused instead
 * of producing a wrong key.
 *
 * The list below is frozen. It holds 2048 lowercase English words of three to
 * eight letters, all distinct and ASCII, curated for Suite from common concrete
 * nouns, verbs and adjectives so they are easy to read, spell and write down.
 * Word order is the encoding: adding, removing or reordering a word would
 * change every phrase ever printed, so this array must never be edited.
 */

