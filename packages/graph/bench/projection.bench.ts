import { LoroDoc, LoroMap, LoroText } from "loro-crdt";
import { afterEach, type Bench, describe, expect, test } from "vitest";
import {
  type ProjectionResult,
  placementKey,
  projectWorkspace,
  WorkspaceDocument,
} from "../src/index.js";

/**
 * Per-room cost of `projectWorkspace`. A selection share multiplies the number
 * of live projection rooms the server keeps per workspace, so a rebuild has to
 * fit a capacity budget: these numbers are how long one room costs.
 *
 * The fixture is synthetic but board-shaped: a handful of types with a few
 * fields, tags, sections, a sparse edge graph, and bodies with two paragraphs
 * and a mention so the rich-text copy path is exercised. Boards are built once
 * per size and reused, so the 200-card selection groups project against the
 * same 2 000 and 5 000-card boards the whole-board groups use.
 *
 * Ids are fixed for boards, sections, cards and types. Field and tag ids are
 * generated by the public API (it does not accept them), so those strings vary
 * between runs while every size and shape stays identical.
 */
const MAIN_BOARD_ID = "board-bench-main";
const SIDE_BOARD_ID = "board-bench-side";
const BOARD_SIZES = [500, 2_000, 5_000] as const;
const SELECTION_CARDS = 200;
const CARD_COLUMNS = 40;
const COLUMN_WIDTH = 280;
const ROW_HEIGHT = 200;
const EDGE_EVERY = 10;
const LINK_EVERY = 20;
const TYPE_IDS = ["concept", "source", "note"] as const;
const TOPICS = ["retrieval", "tooling", "protocol", "diagrams", "interfaces"] as const;
const BODY_LINE =
  "A paragraph of thinking about the card, its neighbours, and the context it lives in. ";
const CREATED_AT = 1_700_000_000_000;
const TEST_TIMEOUT_MS = 180_000;

function writeParagraph(container: LoroMap, text: string): void {
  const children = container.ensureMergeableList("children");
  const paragraph = children.insertContainer(children.length, new LoroMap());
  paragraph.set("nodeName", "paragraph");
  paragraph.ensureMergeableMap("attributes");
  const inline = paragraph.ensureMergeableList("children");
  inline.insertContainer(0, new LoroText()).insert(0, text);
}

function writeMention(container: LoroMap, cardId: string): void {
  const children = container.ensureMergeableList("children");
  const paragraph = children.insertContainer(children.length, new LoroMap());
  paragraph.set("nodeName", "paragraph");
  paragraph.ensureMergeableMap("attributes");
  const inline = paragraph.ensureMergeableList("children");
  const mention = inline.insertContainer(0, new LoroMap());
  mention.set("nodeName", "mention");
  mention.ensureMergeableMap("attributes").set("cardId", cardId);
}

function mainCardId(index: number): string {
  return `card-${String(index).padStart(6, "0")}`;
}

function sideCardId(index: number): string {
  return `side-${String(index).padStart(4, "0")}`;
}

interface Fixture {
  workspace: WorkspaceDocument;
  selection: string[];
}

const fixtures = new Map<number, Fixture>();

function fixture(cards: number): Fixture {
  const existing = fixtures.get(cards);
  if (existing) return existing;
  const built = buildWorkspace(cards);
  fixtures.set(cards, built);
  return built;
}

function buildWorkspace(cards: number): Fixture {
  const workspace = new WorkspaceDocument(new LoroDoc());
  workspace.ensureDefaultTypes();
  const board = workspace.createBoard({ id: MAIN_BOARD_ID, name: "Bench board" });
  workspace.createBoard({ id: SIDE_BOARD_ID, name: "Side board" });

  const status = workspace.addField("concept", {
    name: "Status",
    kind: "select",
    options: ["Draft", "Active", "Done"],
  });
  const summary = workspace.addField("concept", { name: "Summary", kind: "text" });
  const related = workspace.addField("concept", { name: "Related", kind: "card" });
  workspace.addField("source", { name: "URL", kind: "text" });
  workspace.addField("source", { name: "Published", kind: "date" });
  const tags = ["reading", "idea", "follow-up"].map((name) => workspace.createTag({ name }));
  const optionIds = status.options.map((option) => option.id);

  const rows = Math.ceil(cards / CARD_COLUMNS);
  const rowSpan = Math.max(1, Math.ceil(rows / 3));
  const colSpan = Math.ceil(CARD_COLUMNS / 3);

  // One transaction, plus placements written directly. `createCard({ boardId })`
  // re-scans every placement of the workspace on every call (placeCardInternal
  // lists and sorts them), which makes building a 5 000-card board take over a
  // minute. These are the same fields placeCardInternal writes, through the
  // exported key helper, so setup stays linear.
  const placements = workspace.doc.getMap(WorkspaceDocument.PLACEMENTS_KEY);
  const place = (boardId: string, cardId: string, x: number, y: number, z: number): void => {
    const fields = placements.ensureMergeableMap(placementKey(boardId, cardId));
    fields.set("boardId", boardId);
    fields.set("cardId", cardId);
    fields.set("x", x);
    fields.set("y", y);
    fields.set("z", z);
    fields.set("createdAt", CREATED_AT + z);
  };

  workspace.batch("bench:build", () => {
    for (let row = 0; row < 3; row += 1) {
      for (let column = 0; column < 3; column += 1) {
        workspace.createSection({
          id: `section-${row}-${column}`,
          boardId: board.id,
          title: `Zone ${row}.${column}`,
          x: column * colSpan * COLUMN_WIDTH,
          y: row * rowSpan * ROW_HEIGHT,
          width: colSpan * COLUMN_WIDTH,
          height: rowSpan * ROW_HEIGHT,
        });
      }
    }
    workspace.createSection({
      id: "section-side",
      boardId: SIDE_BOARD_ID,
      title: "Side",
      x: 0,
      y: 0,
      width: 3_000,
      height: 2_000,
    });

    for (let index = 0; index < cards; index += 1) {
      const id = mainCardId(index);
      const typeId = TYPE_IDS[index % TYPE_IDS.length] ?? "note";
      workspace.createCard({ id, typeId });
      place(
        board.id,
        id,
        (index % CARD_COLUMNS) * COLUMN_WIDTH,
        Math.floor(index / CARD_COLUMNS) * ROW_HEIGHT,
        index,
      );
      writeParagraph(
        workspace.getTitle(id),
        `Card ${index} ${TOPICS[index % TOPICS.length] ?? "topic"}`,
      );
      writeParagraph(workspace.getContent(id), `${BODY_LINE}Entry ${index}.`);
      writeParagraph(workspace.getContent(id), `${BODY_LINE}Continued ${index}.`);
      writeMention(workspace.getContent(id), mainCardId((index + 1) % cards));

      if (typeId === "concept") {
        const optionId = optionIds[index % optionIds.length];
        if (optionId) workspace.setProperty(id, status.id, optionId);
        workspace.setProperty(id, summary.id, `Summary of card ${index}`);
        if (index % LINK_EVERY === 0) {
          workspace.setProperty(id, related.id, mainCardId((index + 7) % cards));
        }
      }
      const tag = tags[index % tags.length];
      if (index % 5 === 0 && tag) workspace.addCardTag(id, tag.id);
      if (index > 0 && index % EDGE_EVERY === 0) {
        workspace.addEdge({ boardId: board.id, source: mainCardId(index - 1), target: id });
      }
    }

    // A second board with its own cards. Some of them mention the big board, so
    // a board share has to redact titles it does not include.
    const sideCards = Math.min(100, Math.max(1, Math.ceil(cards / 20)));
    for (let index = 0; index < sideCards; index += 1) {
      const id = sideCardId(index);
      workspace.createCard({ id, typeId: "source" });
      place(
        SIDE_BOARD_ID,
        id,
        (index % 15) * COLUMN_WIDTH,
        Math.floor(index / 15) * ROW_HEIGHT,
        index,
      );
      writeParagraph(workspace.getTitle(id), `Source ${index}`);
      writeParagraph(workspace.getContent(id), `${BODY_LINE}Source ${index}.`);
      if (index % 3 === 0) {
        writeMention(workspace.getContent(id), mainCardId((index * 17) % cards));
      }
      if (index > 0 && index % EDGE_EVERY === 0) {
        workspace.addEdge({
          boardId: SIDE_BOARD_ID,
          source: sideCardId(index - 1),
          target: id,
        });
      }
    }
  });

  // Evenly spaced cards, so a selection spans sections, edges and properties.
  const selection = Array.from({ length: SELECTION_CARDS }, (_, step) =>
    mainCardId(Math.floor((step * cards) / SELECTION_CARDS)),
  );

  return { workspace, selection };
}

function projectedBytes(result: ProjectionResult): number {
  return result.workspace.doc.export({ mode: "snapshot" }).length;
}

function formatBytes(bytes: number): string {
  if (bytes >= 1024 * 1024) return `${(bytes / (1024 * 1024)).toFixed(2)} MiB`;
  return `${(bytes / 1024).toFixed(1)} KiB`;
}

/** One tidy line per group: the size of the document a share room would hold. */
function report(scope: string, cards: number, result: ProjectionResult): void {
  const bytes = projectedBytes(result);
  console.log(
    `[projection] ${scope} (${cards} cards) -> ${formatBytes(bytes)} / ${bytes} B, ${result.references.length} reference rows`,
  );
}

/**
 * Each group builds its own fixture and drops it afterwards. Vitest runs a
 * bench file in one worker, and holding a 500-card, a 2 000-card and a 5 000-card
 * document at once makes the Loro WASM heap panic (`RuntimeError: unreachable`)
 * partway through. One fixture at a time keeps the run green; the cost is
 * rebuilding the larger fixture for its second group.
 */
afterEach(() => {
  fixtures.clear();
});

interface Schedule {
  warmupIterations: number;
  iterations: number;
  /** Iteration counts govern, not wall-clock budgets. */
  time: number;
  warmupTime: number;
}

/**
 * Iteration counts keep the whole file under about a minute: a whole-board
 * projection at 5 000 cards costs ~20 s, and the harness runs every group once
 * before the measured iterations, so each group already pays for a warm run.
 *
 * These are bench-level run options (`registration.run(...)`): the options
 * passed to `bench(name, options, fn)` are per-task lifecycle hooks, so an
 * `iterations` value there is ignored and tinybench falls back to its defaults
 * (16 warmups + 64 runs). `time`/`warmupTime` are pinned to 0 so the iteration
 * counts govern instead of wall-clock budgets.
 */
function scheduleFor(scope: "board" | "selection", cards: number): Schedule {
  const base = { time: 0, warmupTime: 0, warmupIterations: 0 };
  // The 500-card board is cheap enough to average two measured runs.
  if (scope === "board" && cards <= 500) return { ...base, iterations: 2 };
  return { ...base, iterations: 1 };
}

/** Runs one projection group and reports the size of the last projected doc. */
async function measure(
  bench: Bench,
  name: string,
  scope: "board" | "selection",
  cards: number,
  run: () => ProjectionResult,
  expected: number,
  boardId: string,
): Promise<void> {
  let last: ProjectionResult | undefined;
  await bench(name, () => {
    last = run();
  }).run(scheduleFor(scope, cards));
  if (!last) throw new Error(`${name} produced no projection`);
  expect(last.workspace.listBoardCards(boardId)).toHaveLength(expected);
  report(scope, cards, last);
  // Drop the last projection before the next group allocates another one.
  last = undefined;
}

describe("projection", () => {
  for (const size of BOARD_SIZES) {
    // The selection groups come first so the 5 000-card selection warms the
    // copy and reference paths before the most expensive full-board run.
    if (size > 500) {
      test(
        `${SELECTION_CARDS}-card selection on ${size} cards`,
        async ({ bench }) => {
          const data = fixture(size);
          await measure(
            bench,
            "project selection",
            "selection",
            size,
            () =>
              projectWorkspace(data.workspace, {
                scope: "selection",
                boardId: MAIN_BOARD_ID,
                cardIds: data.selection,
              }),
            SELECTION_CARDS,
            MAIN_BOARD_ID,
          );
        },
        TEST_TIMEOUT_MS,
      );
    }

    test(
      `board ${size} cards`,
      async ({ bench }) => {
        const data = fixture(size);
        await measure(
          bench,
          "project whole board",
          "board",
          size,
          () => projectWorkspace(data.workspace, { scope: "board", boardId: MAIN_BOARD_ID }),
          size,
          MAIN_BOARD_ID,
        );
        // The selection group already used it; free the board before the next
        // size allocates its own.
        fixtures.delete(size);
      },
      TEST_TIMEOUT_MS,
    );
  }
});
