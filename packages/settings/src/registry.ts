/**
 * Every setting the panel can change, in one table.
 *
 * The reason this is a registry rather than a form per feature: a setting is a fact about
 * the deployment that the app can re-read on the next request, and adding one should be a
 * line here rather than a route, a column, a validator and a control. The kinds are small
 * on purpose — a string, a number, a boolean, an enum or a secret — because anything
 * richer belongs in the feature that owns it.
 *
 * ## What is not here
 *
 * A value the process needs *before* it can read the database cannot live in the database.
 * The database URL, the key that decrypts these values, the session secret, the ports and
 * the data directory stay in `.env`, generated by `pnpm setup`, and the panel shows them
 * read-only. That boundary is `BOOTSTRAP_VARIABLES` below, and it is the whole answer to
 * "why can't I change this from the panel?".
 */

/** How a value is parsed, stored and rendered. */
export type SettingKind = "string" | "number" | "boolean" | "enum" | "secret";

export interface SettingDefinition {
  /** Dotted name, the only identifier a caller and the panel share. */
  key: string;
  kind: SettingKind;
  /** The values an `enum` accepts; ignored for every other kind. */
  values?: readonly string[];
  /**
   * The environment variable that supplies the boot default.
   *
   * A deployment that already sets it keeps working: the panel marks the value as coming
   * from the environment until somebody saves a row.
   */
  env?: string;
  /** What the value is when neither the database nor the environment supplies one. */
  fallback: string;
  /** Whether an organization may hold its own value for this key. */
  overridable?: boolean;
  /** Grouping for the panel, and nothing else. */
  group: "billing" | "mail" | "licence" | "backup" | "limits" | "flags";
  /** One sentence, shown beside the field. */
  help: string;
}

