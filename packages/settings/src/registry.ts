/** The definitions, by key, for a lookup that is not a scan. */
export const SETTINGS_BY_KEY: ReadonlyMap<string, SettingDefinition> = new Map(
  SETTINGS.map((definition) => [definition.key, definition]),
);

/** Whether a key exists at all: the API refuses unknown names rather than creating rows. */
export function settingDefinition(key: string): SettingDefinition | null {
  return SETTINGS_BY_KEY.get(key) ?? null;
}

