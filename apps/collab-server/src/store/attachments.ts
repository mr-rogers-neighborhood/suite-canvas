import { mkdirSync } from "node:fs";
import { dirname } from "node:path";
import { DatabaseSync } from "node:sqlite";
import { formatBytes, resolveLimits } from "../config/limits.js";
import { configureConnection } from "./persistence.js";

/**
 * Attachment bytes beside the document.
 *
 * A card body stores an `attachment` node whose attributes are metadata only —
 * id, mime, width, height, name and byte count. The bytes themselves live here,
 * behind an opaque id, so a share projection (which copies the document) never
 * carries a private copy of every image: a projection stores the id and the
 * viewer fetches the bytes once, from the same relay.
 *
 * Ids are 128 random bits in hex. That is the whole read credential: a GET needs
 * nothing else, so the id must be unguessable. It is generated by the client so
 * that a locally-stored copy made before an upload keeps the same identity.
 */

/** Types the relay accepts and serves. Anything else is refused at upload. */
export const ATTACHMENT_MIME_TYPES = [
  "image/png",
  "image/jpeg",
  "image/gif",
  "image/webp",
  "image/avif",
  "video/mp4",
  "video/webm",
  "video/ogg",
  "video/quicktime",
] as const;

export type AttachmentMime = (typeof ATTACHMENT_MIME_TYPES)[number];

/**
 * Largest single upload. The per-workspace cap in `limits.ts` is the quota; this
 * is the memory bound one request may reach before the body is even stored.
 */
export const MAX_ATTACHMENT_BYTES = 100 * 1024 * 1024;

/** Schema version stamped into `PRAGMA user_version`; bump only with a migration. */
export const ATTACHMENT_STORE_SCHEMA = 1;

/** A 128-bit id, lowercase hex. */
export const ATTACHMENT_ID_PATTERN = /^[0-9a-f]{32}$/u;

/** Longest name a node may carry; it is alt text, not a filename. */
export const MAX_ATTACHMENT_NAME = 200;

/** Lowercase and drop `; charset=…` and stray whitespace. */
export function normalizeMime(value: string | undefined | null): string {
  if (typeof value !== "string") return "";
  return value.split(";")[0]?.trim().toLowerCase() ?? "";
}

export function isAttachmentMime(value: string | undefined | null): value is AttachmentMime {
  const mime = normalizeMime(value);
  return (ATTACHMENT_MIME_TYPES as readonly string[]).includes(mime);
}

/**
 * The one content-type allowlist. Returns null when the type is accepted, or a
 * readable refusal naming the reason — an SVG is refused because it is markup
 * that can carry script, and an HTML page is refused because an attachment is
 * bytes, never a document the relay would host.
 */
export function attachmentMimeProblem(value: string | undefined | null): string | null {
  const mime = normalizeMime(value);
  if ((ATTACHMENT_MIME_TYPES as readonly string[]).includes(mime)) return null;
  if (mime === "image/svg+xml") {
    return "SVG is not accepted: an SVG is markup and can carry script. Upload a PNG, JPEG, GIF, WebP, AVIF image or MP4, WebM, OGG, QuickTime video instead.";
  }
  if (mime === "text/html" || mime === "application/xhtml+xml" || mime === "text/xml") {
    return "HTML is not accepted: attachments are media bytes, and the relay never hosts a page. Upload a supported image or video instead.";
  }
  return `Unsupported attachment type "${mime || "unknown"}"; the relay accepts ${ATTACHMENT_MIME_TYPES.join(", ")}.`;
}

/** Bytes a workspace may store, from `limits.ts`. */
export function attachmentCap(env: NodeJS.ProcessEnv = process.env): number {
  return resolveLimits(env).limits.attachmentBytesPerWorkspace;
}

/** Where the disk-backed store keeps its rows. */
export function attachmentDatabasePath(env: NodeJS.ProcessEnv = process.env): string {
  return env.SUITE_ATTACHMENTS_DB?.trim() || "suite.attachments.sqlite";
}

export function newAttachmentId(): string {
  return randomBytes(16).toString("hex");
}

/** One stored attachment without its bytes. */
export interface AttachmentMeta {
  id: string;
  workspaceId: string;
  /** A type from the allowlist for anything `put` stored; hand-edited rows are re-checked before they are served. */
  mime: string;
  size: number;
  createdAt: number;
}

/** One stored attachment with the bytes it describes. */
export interface AttachmentRecord extends AttachmentMeta {
  bytes: Uint8Array;
}

/** What a `put` may name explicitly. */
export interface PutAttachmentOptions {
  /** Client-chosen id, so a locally stored copy keeps its identity after upload. */
  id?: string;
}

/**
 * The byte store. This interface *is* the seam for object storage.
 *
 * Only `createSqliteAttachmentStore` ships: one disk-backed table beside the
 * document store, which fits a single-instance relay with no extra service.
 * An S3 backend would implement the same interface with the object key
 * `attachments/<workspaceId>/<id>` (server-side encryption on, a lifecycle rule
 * as a backstop) and add `signedRead`: instead of proxying bytes through Node,
 * `GET` answers a 302 to a pre-signed, read-only URL with a ~60 second life, so
 * the relay never streams image data and a leaked URL dies quickly. `put` would
 * write the object first and the row second (an orphaned object is harmless and
 * the lifecycle rule collects it); `gc` would delete the row and then the
 * object, so a failed object delete leaves a row to retry rather than bytes no
 * row points at.
 */
export interface AttachmentStore {
  put: (
    workspaceId: string,
    bytes: Uint8Array,
    mime: string,
    options?: PutAttachmentOptions,
  ) => AttachmentMeta;
  get: (id: string) => AttachmentRecord | null;
  delete: (id: string) => boolean;
  /** Bytes stored for one workspace, the number the cap compares against. */
  usage: (workspaceId: string) => number;
  /** Bytes stored across multiple workspaces. */
  usageForWorkspaces: (workspaceIds: readonly string[]) => number;
  /** Deletes every row of `workspaceId` whose id is not in `referencedIds`. */
  gc: (workspaceId: string, referencedIds: Iterable<string>) => number;
  /**
   * Object-storage hook: a short-lived read URL, or null to serve the bytes.
   * The disk store leaves it undefined; the HTTP route checks for it.
   */
  signedRead?: (id: string, ttlMs: number) => Promise<{ url: string; expiresAt: number } | null>;
  close: () => void;
}

/** A put refused because the workspace is at its attachment cap. */
export class AttachmentCapError extends Error {
  readonly reason = "attachment-cap";

  constructor(
    readonly used: number,
    readonly cap: number,
    readonly size: number,
  ) {
    super(
      `This workspace's attachments use ${formatBytes(used)} of ${formatBytes(cap)}; this ${formatBytes(size)} image would go over. Delete an attachment, or raise SUITE_ATTACHMENT_BYTES_PER_WORKSPACE.`,
    );
    this.name = "AttachmentCapError";
  }
}

/** A put refused because the id is already taken. */
export class AttachmentExistsError extends Error {
  readonly reason = "attachment-exists";

  constructor(readonly id: string) {
    super("An attachment with this id already exists.");
    this.name = "AttachmentExistsError";
  }
}

interface UsageRow {
  bytes: number | null;
}

interface Row {
  id: string;
  workspace_id: string;
  mime: string;
  bytes: Uint8Array;
  size: number;
  created_at: number;
}

interface IdRow {
  id: string;
}

export interface SqliteAttachmentOptions {
  /**
   * Per-workspace byte cap, read on every put so a runtime override applies
   * without reopening the file. Defaults to `limits.ts` (env + defaults).
   */
  cap?: () => number;
  now?: () => number;
}

/**
 * Opens the table once and migrates nothing: attachments are new, so there is no
 * older shape to read.
 */
export function createSqliteAttachmentStore(
  path: string,
  options: SqliteAttachmentOptions = {},
): AttachmentStore {
  if (path !== ":memory:") mkdirSync(dirname(path), { recursive: true });
  const db = new DatabaseSync(path);
  // WAL, the busy timeout and the schema stamp in one place; a GET then waits
  // for a PUT instead of failing with SQLITE_BUSY.
  configureConnection(db, ATTACHMENT_STORE_SCHEMA);
  db.exec(
    `CREATE TABLE IF NOT EXISTS attachments (
       id TEXT PRIMARY KEY,
       workspace_id TEXT NOT NULL,
       mime TEXT NOT NULL,
       bytes BLOB NOT NULL,
       size INTEGER NOT NULL,
       created_at INTEGER NOT NULL
     );
     CREATE INDEX IF NOT EXISTS attachments_workspace ON attachments (workspace_id);`,
  );

  const insert = db.prepare(
    `INSERT INTO attachments (id, workspace_id, mime, bytes, size, created_at)
     VALUES (?, ?, ?, ?, ?, ?)
     ON CONFLICT(id) DO NOTHING`,
  );
  const select = db.prepare("SELECT * FROM attachments WHERE id = ?");
  const remove = db.prepare("DELETE FROM attachments WHERE id = ?");
  const removeOne = db.prepare("DELETE FROM attachments WHERE workspace_id = ? AND id = ?");
  const idsOfWorkspace = db.prepare("SELECT id FROM attachments WHERE workspace_id = ?");
  const sumOfWorkspace = db.prepare(
    "SELECT COALESCE(SUM(size), 0) AS bytes FROM attachments WHERE workspace_id = ?",
  );

  const now = options.now ?? Date.now;
  const cap = options.cap ?? attachmentCap;

  const usage = (workspaceId: string): number => {
    const row = sumOfWorkspace.get(workspaceId) as UsageRow | undefined;
    return Number(row?.bytes ?? 0);
  };

  const usageForWorkspaces = (workspaceIds: readonly string[]): number => {
    const valid = workspaceIds.map((id) => id.trim()).filter((id) => id.length > 0);
    if (valid.length === 0) return 0;
    const placeholders = valid.map(() => "?").join(",");
    const stmt = db.prepare(
      `SELECT COALESCE(SUM(size), 0) AS bytes FROM attachments WHERE workspace_id IN (${placeholders})`,
    );
    const row = stmt.get(...valid) as UsageRow | undefined;
    return Number(row?.bytes ?? 0);
  };

  return {
    put: (workspaceId, bytes, mime, putOptions = {}) => {
      const id = putOptions.id ?? newAttachmentId();
      if (!ATTACHMENT_ID_PATTERN.test(id)) {
        throw new Error("An attachment id must be 32 lowercase hex characters.");
      }
      if (workspaceId.trim().length === 0) {
        throw new Error("An attachment needs a workspace.");
      }
      const problem = attachmentMimeProblem(mime);
      if (problem !== null) throw new Error(problem);

      const size = bytes.byteLength;
      const normalised = normalizeMime(mime) as AttachmentMime;
      const createdAt = now();

      db.exec("BEGIN IMMEDIATE");
      try {
        const used = usage(workspaceId);
        const limit = cap();
        // The cap is checked against committed rows inside the write
        // transaction, so two uploads racing cannot both slip under it.
        if (Number.isFinite(limit) && used + size > limit) {
          throw new AttachmentCapError(used, limit, size);
        }
        const result = insert.run(
          id,
          workspaceId,
          normalised,
          Buffer.from(bytes.buffer, bytes.byteOffset, bytes.byteLength),
          size,
          createdAt,
        );
        if (Number(result.changes) !== 1) throw new AttachmentExistsError(id);
        db.exec("COMMIT");
      } catch (error) {
        db.exec("ROLLBACK");
        throw error;
      }

      return { id, workspaceId, mime: normalised, size, createdAt };
    },

    get: (id) => {
      if (!ATTACHMENT_ID_PATTERN.test(id)) return null;
      const row = select.get(id) as Row | undefined;
      if (!row) return null;
      return {
        id: row.id,
        workspaceId: row.workspace_id,
        // Rows written through `put` passed the allowlist; a hand-edited row is
        // re-checked by the HTTP route before it is served.
        mime: row.mime,
        bytes: new Uint8Array(row.bytes),
        size: Number(row.size),
        createdAt: Number(row.created_at),
      };
    },

    delete: (id) => {
      if (!ATTACHMENT_ID_PATTERN.test(id)) return false;
      return Number(remove.run(id).changes) > 0;
    },

    usage,
    usageForWorkspaces,

    gc: (workspaceId, referencedIds) => {
      const keep = new Set(referencedIds);
      const rows = idsOfWorkspace.all(workspaceId) as unknown as IdRow[];
      let removed = 0;
      db.exec("BEGIN IMMEDIATE");
      try {
        for (const row of rows) {
          if (keep.has(row.id)) continue;
          removed += Number(removeOne.run(workspaceId, row.id).changes);
        }
        db.exec("COMMIT");
      } catch (error) {
        db.exec("ROLLBACK");
        throw error;
      }
      return removed;
    },

    close: () => db.close(),
  };
}

/**
 * Collects the attachments a workspace no longer references. Operators call this
 * after a document edit that removed images; nothing schedules it, because a
 * timer would delete bytes while an editor still holds a paste in flight.
 *
 * The caller passes the ids the document still references — the attachment node
 * ids in every card body — and every other row of that workspace is deleted.
 */
export function gcAttachments(
  workspaceId: string,
  referencedIds: Iterable<string>,
  store: AttachmentStore = defaultAttachmentStore(),
): number {
  if (workspaceId.trim().length === 0) throw new Error("A workspace id is required.");
  return store.gc(workspaceId, referencedIds);
}

let shared: AttachmentStore | null = null;

/**
 * The process-wide disk store. `cap` is only read the first time: the server
 * passes a live accessor, so later limit changes still apply.
 */
export function defaultAttachmentStore(cap?: () => number): AttachmentStore {
  shared ??= createSqliteAttachmentStore(
    attachmentDatabasePath(),
    cap === undefined ? {} : { cap },
  );
  return shared;
}

/** Test seam: forget the process-wide store so the next call reopens its file. */
export function resetDefaultAttachmentStore(): void {
  shared?.close();
  shared = null;
}
